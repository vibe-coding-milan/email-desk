import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = readFileSync(new URL('../public/app.js', import.meta.url),'utf8');
const engine = source.split('// Guest day engine:')[1].split('// End guest day engine.')[0];
const context = vm.createContext({Date});
vm.runInContext('// Guest day engine:' + engine, context);
const batches = Array.from({length:3},(_,stage) => Array.from({length:4},(_,i) => ({id:`${stage}-${i}`,category:i<2?'action':'awareness'})));
const state = context.createGuestDay(batches);
assert.equal(state.xp,0);
assert.equal(state.now,Date.parse('2026-11-16T14:00:00Z'));
assert.equal(context.advanceGuestDay(state,6000,batches),false,'Reading cards must not advance reviews');
assert.equal(context.resolveGuestCard(state,'unknown','handled'),0);
assert.equal(context.resolveGuestCard(state,'0-0','open'),0);
context.resolveGuestCard(state,'0-0','handled');
assert.equal(context.resolveGuestCard(state,'0-0','dismissed'),0,'A retry never awards XP twice');
state.cards[0].note='Keep my context';
for (const c of state.cards.slice(1)) context.resolveGuestCard(state,c.id,'dismissed');
assert.equal(state.xp,40); assert(state.travelling);
assert.equal(context.advanceGuestDay(state,-1,batches),false);
assert.equal(context.advanceGuestDay(state,NaN,batches),false);
context.advanceGuestDay(state,3000,batches);
assert.equal(state.now,Date.parse('2026-11-16T16:00:00Z'),'Half a transition represents 11 AM');
assert.equal(state.cards.length,4,'No new cards before the publication boundary');
assert.equal(state.stage,0);
context.advanceGuestDay(state,1500,batches);
assert.equal(state.now,Date.parse('2026-11-16T17:00:00Z'),'Three quarters represents noon');
assert(context.advanceGuestDay(state,1500,batches));
assert.equal(state.stage,1); assert.equal(state.cards.length,8);
assert.equal(state.cards[0].note,'Keep my context');
assert.equal(state.cards[0].state,'handled');
assert.equal(context.advanceGuestDay(state,6000,batches),false,'One arrival cannot duplicate its batch');
for (const c of state.cards.filter(c=>c.state==='open')) context.resolveGuestCard(state,c.id,'handled');
assert.equal(state.xp,80);
context.advanceGuestDay(state,6000,batches);
assert.equal(state.stage,2); assert.equal(state.cards.length,12);
for (const c of state.cards.filter(c=>c.state==='open').slice(0,2)) context.resolveGuestCard(state,c.id,'handled');
assert.equal(state.xp,100); assert.equal(Math.floor(state.xp/100)+1,2);
for (const c of state.cards.filter(c=>c.state==='open')) context.resolveGuestCard(state,c.id,'dismissed');
assert.equal(state.xp,120); assert.equal(state.travelling,false);
assert.equal(context.advanceGuestDay(state,60000,batches),false);
const fresh = context.createGuestDay(batches);
assert.equal(fresh.cards.length,4); assert.equal(fresh.xp,0); assert.equal(fresh.cards[0].note,'');
assert.equal(batches[0][0].state,undefined,'Never mutate the template batch');
console.log('Guest day: publication boundaries, proportional time, three batches, preserved history/context, deduplicated XP, level-up and reset passed.');

// Empty columns must distinguish a saved clear board from missing coverage.
const emptySource = 'function emptyColumnCopy' + source.split('function emptyColumnCopy')[1].split('function emptyColumn(')[0];
vm.runInContext(emptySource,context);
for (const category of ['action','awareness']) {
  const waiting = context.emptyColumnCopy(category,'waiting');
  const uncertain = context.emptyColumnCopy(category,'unconfirmed');
  const clear = context.emptyColumnCopy(category,'clear');
  assert.match(waiting.detail,/first review/);
  assert.match(uncertain.detail,/unconfirmed/);
  assert.match(uncertain.detail,/does not mean the inbox is clear/);
  assert.match(clear.detail,/saved review|next review/i);
  assert.notEqual(waiting.title,clear.title);
  assert.notEqual(uncertain.title,clear.title);
}
console.log('Empty states distinguish first review, unconfirmed coverage and cleared saved cards in both columns.');
